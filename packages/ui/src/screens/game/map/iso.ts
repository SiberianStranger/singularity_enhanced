/** Lowercase alpha-2 code for a topojson feature id, or null when the atlas has no code for it. */
export function alpha2FromFeatureId(id: string | number | undefined): string | null {
  if (id === undefined) {
    return null;
  }
  return NUMERIC_TO_ALPHA2[String(id)] ?? null;
}
